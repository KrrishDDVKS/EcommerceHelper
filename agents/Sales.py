def get_sales():

    conn = sqlite3.connect(DB_NAME)

    try:
        df = pd.read_sql_query(
            "SELECT * FROM sales",
            conn
        )

        return df

    finally:
        conn.close()


# =========================================================
# 4. SQL Execution Tool
# =========================================================

@tool
def execute_sql(query: str) -> str:
    """
    Execute exactly one SQL statement against the SQLite database.

    This tool is responsible for executing the SQL generated by
    the sales agent.
    """

    query = query.strip()

    # -----------------------------------------------------
    # Safety check
    # -----------------------------------------------------

    statements = [
        statement.strip()
        for statement in query.split(";")
        if statement.strip()
    ]

    if len(statements) != 1:
        return (
            "SQL BLOCKED: Only one SQL statement is allowed "
            "per sales request."
        )

    sql = statements[0]

    # -----------------------------------------------------
    # Only INSERT into sales is allowed
    # -----------------------------------------------------

    if not sql.upper().startswith("INSERT"):
        return (
            "SQL BLOCKED: Only INSERT statements are allowed "
            "by the sales SQL tool."
        )

    if "SALES" not in sql.upper():
        return (
            "SQL BLOCKED: INSERT must target the sales table."
        )

    conn = sqlite3.connect(DB_NAME)

    try:

        cursor = conn.cursor()

        cursor.execute(sql)

        conn.commit()

        result = (
            "Sales record inserted successfully.\n"
            f"Rows affected: {cursor.rowcount}"
        )

        return result

    except Exception as e:

        conn.rollback()

        return f"SQL execution failed: {e}"

    finally:

        conn.close()


